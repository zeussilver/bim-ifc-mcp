"""BCF 2.1 export: rule-check issues as topics BIMcollab, Solibri, Archicad or Revit (via a BCF add-in) can open.

BCF (BIM Collaboration Format) is buildingSMART's zip-of-XML format for passing
model issues between tools. Each issue becomes one topic that selects the
offending element by its IFC GlobalId and, when a model is given, a viewpoint
that frames it: a clipping plane just above the element (or through a room at
plan-cut height) hides the floors above, and the camera looks down at it from
the side with the clearest sight line. Each viewpoint carries a plain
placeholder snapshot, which BIMcollab needs before it will open the viewpoint.

Conventions:
  - Topic and viewpoint GUIDs are uuid5 of (rule_id, global_id), so re-exporting
    after a model update updates the same topics instead of duplicating them.
  - TopicType is "Error" for FAIL and "Request" for UNKNOWN: missing model data
    is a request for information to the modeller, not a confirmed defect.
  - Every topic says it is a screening result that needs human review.

Element order follows the official BCF 2.1 XSDs (buildingSMART/BCF-XML, branch
release_2_1, Schemas/*.xsd). xs:sequence is ordered, so strict importers reject
children in the wrong order; each writer below names the sequence it follows.
"""

import math
import re
import struct
import uuid
import xml.etree.ElementTree as ET
import zipfile
import zlib
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

import ifcopenshell
import ifcopenshell.util.placement as placement_util
import ifcopenshell.util.unit as unit_util

from bim_ifc_mcp.geometry import blocked_sightlines, element_bboxes, scene_mesh

# Fixed forever: changing it would orphan topics people already imported.
NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "urn:bim-ifc-mcp:bcf")
PRIORITY = {"critical": "Critical", "major": "Major", "minor": "Minor", "info": "Normal"}
TOPIC_TYPE = {"FAIL": "Error", "UNKNOWN": "Request"}
# Viewpoint framing. BCF 2.1 FieldOfView is horizontal; on a 16:9 screen that leaves about 36 degrees
# vertically, which is what the element has to fit in.
FIELD_OF_VIEW = 60.0
VERTICAL_FOV = 2 * math.atan(math.tan(math.radians(FIELD_OF_VIEW / 2)) * 9 / 16)
CLIP_ABOVE_M = 0.2  # clipping plane this far above a door or window head ...
PLAN_CUT_M = 1.5  # ... or through a room at floor-plan cut height, so the floor above never hides it
MIN_DISTANCE_M = 4.0  # far enough back to show the element's surroundings
FACING = ("IfcDoor", "IfcWindow")  # viewed across their wall (placement Y axis), from either side
# A sight line that only just clears a cut wall top counts as blocked: in BIMcollab Zoom such a
# grazing line left the bottom of door A104 hidden behind the wall in front of it.
SIGHT_MARGIN_M = 0.15
DISCLAIMER = "Screening result generated by bim-ifc-mcp – requires review by a qualified person."
# Characters XML 1.0 forbids. ElementTree writes them raw, which makes the whole member unreadable,
# and IFC strings can carry them (a Word line break pasted into a Revit Mark arrives as U+000B).
XML_INVALID = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\ud800-\udfff\ufffe\uffff]")


def _png(width: int, height: int, rgb: tuple[int, int, int]) -> bytes:
    """A solid-colour PNG, written with the standard library."""
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    row = b"\x00" + bytes(rgb) * width  # filter type 0, then RGB pixels
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)  # 8-bit RGB
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(row * height, 9))
            + chunk(b"IEND", b""))


# BIMcollab Zoom ignores a BCF 2.1 viewpoint ("This issue has no viewpoint to zoom to") unless the
# topic also has snapshot.png, although the XSD makes Snapshot optional (IfcOpenShell issue #7152;
# reproduced with Zoom 9.9). Nothing is rendered here, so every topic gets this neutral placeholder.
SNAPSHOT = _png(160, 120, (224, 224, 224))


def _guid(*parts) -> str:
    return str(uuid.uuid5(NAMESPACE, "|".join(str(p) for p in parts)))


def _xml(value) -> str:
    return XML_INVALID.sub(" ", str(value))


def _sub(parent: ET.Element, tag: str, text=None, **attrib) -> ET.Element:
    el = ET.SubElement(parent, tag, {k: _xml(v) for k, v in attrib.items()})
    if text is not None:
        el.text = _xml(text)
    return el


def _num(v: float) -> str:
    return str(round(v, 4) + 0.0)  # + 0.0 turns -0.0 into 0.0


def _unit(v) -> np.ndarray:
    v = np.asarray(v, float)
    return v / np.linalg.norm(v)


def _look(target, heading, pitch_deg: float, distance: float):
    """(eye, direction, up) in metres: look at target along a horizontal heading, pitched down."""
    pitch = math.radians(pitch_deg)
    h = _unit([heading[0], heading[1], 0.0])
    d = np.array([h[0] * math.cos(pitch), h[1] * math.cos(pitch), -math.sin(pitch)])
    up = _unit(np.array([0.0, 0.0, 1.0]) - d * d[2])  # world +Z made orthogonal to the view direction
    return np.asarray(target, float) - d * distance, d, up


def _rotate(v, degrees: float) -> list[float]:
    a = math.radians(degrees)
    return [v[0] * math.cos(a) - v[1] * math.sin(a), v[0] * math.sin(a) + v[1] * math.cos(a)]


def _across(el) -> np.ndarray | None:
    """Horizontal normal of a door's or window's wall (its placement Y axis), or None."""
    if not any(el.is_a(c) for c in FACING):
        return None
    placement = getattr(el, "ObjectPlacement", None)
    if placement is None or not placement.is_a("IfcLocalPlacement"):
        return None
    y_axis = placement_util.get_local_placement(placement)[:3, 1]
    return y_axis if math.hypot(y_axis[0], y_axis[1]) > 1e-6 else None


def _framed_view(el, lo: np.ndarray, hi: np.ndarray, mesh):
    """(camera, clipping-plane point) framing an element's world bounding box.

    A door or window is watched across its wall from either side, square-on or 30 degrees
    off, at 50, 65 or 80 degrees down; the sample points are its face from the floor up
    (its head hides behind the lintel from above anyway). Anything else, i.e. a room, is
    watched diagonally at 60, 75 or 85 degrees, sampling its floor. The camera with the
    fewest blocked sight lines wins; on a tie the shallowest and first, so output is stable.
    """
    centre, size = (lo + hi) / 2, hi - lo
    across = _across(el)
    if across is not None:
        clip_z = hi[2] + CLIP_ABOVE_M
        along = _unit([-across[1], across[0], 0.0])
        half_width = abs(size @ along) / 2
        samples = [centre + along * f * half_width + [0, 0, lo[2] + g * size[2] - centre[2]]
                   for f in (-0.8, -0.4, 0, 0.4, 0.8) for g in (0.01, 0.25, 0.5, 0.75)]
        headings = [_rotate(s * across, yaw) for s in (1, -1) for yaw in (0, 30, -30)]
        pitches = (50.0, 65.0, 80.0)
    else:
        clip_z = min(lo[2] + PLAN_CUT_M, hi[2]) if el.is_a("IfcSpace") else hi[2] + CLIP_ABOVE_M
        xs, ys = np.linspace(lo[0], hi[0], 5)[1:-1], np.linspace(lo[1], hi[1], 5)[1:-1]
        samples = [[x, y, lo[2] + min(0.1, size[2] / 2)] for x in xs for y in ys]
        headings = [_rotate([1.0, 1.0], 90 * k) for k in range(4)]
        pitches = (60.0, 75.0, 85.0)
    distance = max(np.linalg.norm(size) / 2 / math.tan(VERTICAL_FOV / 2) * 1.3, MIN_DISTANCE_M)
    cameras = [_look(centre, h, pitch, distance) for pitch in pitches for h in headings]
    camera = min(cameras, key=lambda c: blocked_sightlines(
        mesh, c[0], samples, below_z=clip_z + SIGHT_MARGIN_M, ignore=el.GlobalId))
    return camera, [centre[0], centre[1], clip_z]


def _views(model: ifcopenshell.file, global_ids: list[str]) -> dict[str, tuple]:
    """{GlobalId: (camera, clipping-plane point or None)} in metres.

    Framed from the element's geometry when it has any. A placement alone is a weak
    fallback (Revit puts most IfcSpaces at the storey origin), so it only gets a plain
    camera on the placement origin and no clipping plane.
    """
    elements = {}
    for global_id in global_ids:
        try:
            elements[global_id] = model.by_guid(global_id)
        except RuntimeError:
            pass
    boxes = element_bboxes(model, elements.values())
    mesh = scene_mesh(model) if boxes else None
    scale = unit_util.calculate_unit_scale(model, "LENGTHUNIT")
    views = {}
    for global_id, el in elements.items():
        placement = getattr(el, "ObjectPlacement", None)
        if global_id in boxes:
            views[global_id] = _framed_view(el, *boxes[global_id], mesh)
        elif placement is not None and placement.is_a("IfcLocalPlacement"):
            origin = placement_util.get_local_placement(placement)[:3, 3] * scale
            views[global_id] = (_look(origin, [1.0, 1.0], 50.0, MIN_DISTANCE_M), None)
    return views


def _version() -> ET.Element:
    # version.xsd  Version: DetailedVersion?   @VersionId
    root = ET.Element("Version", VersionId="2.1")
    _sub(root, "DetailedVersion", "2.1")
    return root


def _project_extension(project) -> ET.Element:
    # project.xsd  ProjectExtension: Project?, ExtensionSchema   Project: Name?   @ProjectId (required)
    root = ET.Element("ProjectExtension")
    proj = _sub(root, "Project", ProjectId=_guid(project.GlobalId))
    if project.Name:
        _sub(proj, "Name", project.Name)
    _sub(root, "ExtensionSchema", "")
    return root


def _file_date(model: ifcopenshell.file) -> str | None:
    """The IFC header's FILE_NAME time stamp as xs:dateTime, or None when it is missing or unparseable."""
    try:
        return datetime.fromisoformat(model.header.file_name.time_stamp).isoformat()
    except (TypeError, ValueError):
        return None


def _markup(issue: dict, topic_guid: str, viewpoint_guid: str, *, project, ifc_filename, file_date, date,
            author) -> ET.Element:
    # markup.xsd  Markup: Header?, Topic, Comment*, Viewpoints*
    root = ET.Element("Markup")
    if project is not None or ifc_filename:
        # Header: File+   File: Filename?, Date?, Reference?   @IfcProject @IfcSpatialStructureElement @isExternal
        attrib = {"IfcProject": project.GlobalId} if project is not None else {}
        file_el = _sub(_sub(root, "Header"), "File", **attrib)
        if ifc_filename:
            _sub(file_el, "Filename", ifc_filename)
        if file_date:  # "Date of the BIM file", not of this export (that is Topic/CreationDate)
            _sub(file_el, "Date", file_date)

    # Topic: ReferenceLink*, Title, Priority?, Index?, Labels*, CreationDate, CreationAuthor, ModifiedDate?,
    #        ModifiedAuthor?, DueDate?, AssignedTo?, Stage?, Description?, BimSnippet?, DocumentReference*,
    #        RelatedTopic*   @Guid (required) @TopicType @TopicStatus
    topic = _sub(root, "Topic", Guid=topic_guid, TopicType=TOPIC_TYPE.get(issue["status"], "Issue"),
                 TopicStatus="Open")
    element = issue.get("element") or issue["global_id"]
    message = issue["message"]
    short = message if len(message) <= 80 else message[:77] + "..."
    _sub(topic, "Title", f"{issue['rule_id']} {element}: {short}")
    _sub(topic, "Priority", PRIORITY.get(issue.get("severity"), "Normal"))
    for label in (issue["rule_id"], issue["ifc_class"]):
        _sub(topic, "Labels", label)
    _sub(topic, "CreationDate", date)
    _sub(topic, "CreationAuthor", author)
    name = f" {issue['element_name']}" if issue.get("element_name") else ""
    lines = [
        message,
        f"Status: {issue['status']}",
        f"Element: {issue['ifc_class']} {element}{name} ({issue['global_id']})",
        f"Storey: {issue.get('storey') or 'unknown'}",
        f"Rule: {issue['rule_id']} {issue.get('rule_title') or ''}".rstrip(),
    ]
    if issue.get("reference"):
        lines.append(f"Reference: {issue['reference']}")
    lines.append(DISCLAIMER)
    _sub(topic, "Description", "\n".join(lines))

    # Viewpoints (type ViewPoint): Viewpoint?, Snapshot?, Index?   @Guid (required)
    # BCF 2.1 fixes the primary viewpoint's file names to viewpoint.bcfv and snapshot.png.
    vp = _sub(root, "Viewpoints", Guid=viewpoint_guid)
    _sub(vp, "Viewpoint", "viewpoint.bcfv")
    _sub(vp, "Snapshot", "snapshot.png")
    return root


def _point(parent: ET.Element, tag: str, vec) -> None:
    # Point / Direction: X, Y, Z
    el = _sub(parent, tag)
    for axis, value in zip("XYZ", vec):
        _sub(el, axis, _num(value))


def _visualization_info(issue: dict, viewpoint_guid: str, view) -> ET.Element:
    # visinfo.xsd  VisualizationInfo: Components?, OrthogonalCamera?, PerspectiveCamera?, Lines?, ClippingPlanes?,
    #              Bitmap*   @Guid (required)
    root = ET.Element("VisualizationInfo", Guid=viewpoint_guid)
    # Components: ViewSetupHints?, Selection?, Visibility, Coloring?
    components = _sub(root, "Components")
    if issue["ifc_class"] == "IfcSpace":
        _sub(components, "ViewSetupHints", SpacesVisible="true")  # viewers hide spaces by default
    # Selection: Component+   Component: OriginatingSystem?, AuthoringToolId?   @IfcGuid
    _sub(_sub(components, "Selection"), "Component", IfcGuid=issue["global_id"])
    # Visibility: Exceptions?   @DefaultVisibility
    _sub(components, "Visibility", DefaultVisibility="true")
    if view is not None:
        camera, clip_point = view
        # PerspectiveCamera: CameraViewPoint, CameraDirection, CameraUpVector, FieldOfView (45..60)
        cam = _sub(root, "PerspectiveCamera")
        for tag, vec in zip(("CameraViewPoint", "CameraDirection", "CameraUpVector"), camera):
            _point(cam, tag, vec)
        _sub(cam, "FieldOfView", _num(FIELD_OF_VIEW))
        if clip_point is not None:
            # ClippingPlanes: ClippingPlane*   ClippingPlane: Location, Direction
            # A horizontal plane over the element. Direction points into the clipped (invisible)
            # half-space, as BCF 3.0 spells out: everything above is hidden, so the floors above
            # cannot block the camera.
            plane = _sub(_sub(root, "ClippingPlanes"), "ClippingPlane")
            _point(plane, "Location", clip_point)
            _point(plane, "Direction", [0.0, 0.0, 1.0])
    return root


def _write(zf: zipfile.ZipFile, name: str, root: ET.Element, now: datetime) -> None:
    ET.indent(root)
    _write_bytes(zf, name, ET.tostring(root, encoding="utf-8", xml_declaration=True), now)


def _write_bytes(zf: zipfile.ZipFile, name: str, data: bytes, now: datetime) -> None:
    info = zipfile.ZipInfo(name, date_time=now.timetuple()[:6])
    info.external_attr = 0o644 << 16
    zf.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED)


def _write_dir(zf: zipfile.ZipFile, name: str, now: datetime) -> None:
    # The BCF 2.1 README requires folder entries in the zip's central directory; some
    # importers find topics by listing them.
    info = zipfile.ZipInfo(f"{name}/", date_time=now.timetuple()[:6])
    info.external_attr = (0o40755 << 16) | 0x10  # drwxr-xr-x plus the MS-DOS directory flag
    zf.writestr(info, b"")


def issues_to_bcf(
    issues: list[dict],
    out_path: str | Path,
    *,
    model: ifcopenshell.file | None = None,
    ifc_filename: str | None = None,
    author: str = "bim-ifc-mcp",
    now: datetime | None = None,
) -> Path:
    """Write issues (rules.evaluate issue dicts) to a BCF 2.1 zip, one topic per issue.

    With `model`, the file also carries project.bcfp, the IfcProject GlobalId, the IFC
    file's date and a viewpoint per element that has geometry or a placement. `now` is
    injectable for repeatable output.
    """
    out = Path(out_path)
    if out.suffix.lower() not in (".bcf", ".bcfzip"):
        raise ValueError(f"BCF output must end in .bcf or .bcfzip, got: {out.name}")

    guids = [_guid(i["rule_id"], i["global_id"]) for i in issues]
    if len(set(guids)) != len(guids):
        raise ValueError("Duplicate (rule_id, global_id) issues would share one BCF topic")

    now = now or datetime.now(timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)
    now = now.astimezone(timezone.utc).replace(microsecond=0)
    date = now.isoformat().replace("+00:00", "Z")
    project = model.by_type("IfcProject")[0] if model is not None else None
    file_date = _file_date(model) if model is not None else None
    views = _views(model, [i["global_id"] for i in issues]) if model is not None else {}

    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w") as zf:
        _write(zf, "bcf.version", _version(), now)
        if project is not None:
            _write(zf, "project.bcfp", _project_extension(project), now)
        for issue, topic_guid in zip(issues, guids):
            viewpoint_guid = _guid(issue["rule_id"], issue["global_id"], "viewpoint")
            view = views.get(issue["global_id"])
            markup = _markup(issue, topic_guid, viewpoint_guid, project=project, ifc_filename=ifc_filename,
                             file_date=file_date, date=date, author=author)
            _write_dir(zf, topic_guid, now)
            _write(zf, f"{topic_guid}/markup.bcf", markup, now)
            _write(zf, f"{topic_guid}/viewpoint.bcfv", _visualization_info(issue, viewpoint_guid, view), now)
            _write_bytes(zf, f"{topic_guid}/snapshot.png", SNAPSHOT, now)
    return out
